Rails.application.routes.draw do
  root "pages#home"

  # Choose which user we are acting as (temporary, until Assignment 4 adds login).
  post "switch_user", to: "users#switch", as: :switch_user

  resources :properties do
    resources :listings, only: [:new, :create]   # a listing is always created inside a property
  end

  resources :listings, only: [:index, :show, :edit, :update, :destroy] do
    member do
      patch :publish
      patch :withdraw
      patch :mark_rented
    end
    resources :applications, only: [:create]      # a seeker applies from the listing page
  end

  resources :applications, only: [:index, :show, :destroy] do
    member do
      patch :shortlist
      patch :reject
      patch :accept
      patch :withdraw
    end
    resources :visits, only: [:create]            # host proposes a visit
  end

  resources :visits, only: [] do
    member do
      patch :confirm
      patch :cancel
      patch :complete
      patch :reschedule
    end
    resources :reviews, only: [:create]           # review written after a completed visit
  end

  resources :neighborhoods
  resources :amenities, except: [:show]

  # Health check endpoint generated by Rails.
  get "up" => "rails/health#show", as: :rails_health_check
end
